/// Centralised font sizes used by the Cineara design system.
///
/// Font size scale:
/// - Label small:   11
/// - Label medium:  13
/// - Label large:   15
/// - Body small:    13
/// - Body medium:   15
/// - Body large:    17
/// - Title small:   18
/// - Title medium:  20
/// - Title large:   24
/// - Display:       32
abstract final class CinearaFontSizes {
  /// Small labels, metadata, and supporting text.
  static const double labelSmall = 11;

  /// Standard labels and compact controls.
  static const double labelMedium = 13;

  /// Prominent labels, buttons, and navigation text.
  static const double labelLarge = 15;

  /// Small supporting body text.
  static const double bodySmall = 13;

  /// Default body text.
  static const double bodyMedium = 15;

  /// Prominent body text.
  static const double bodyLarge = 17;

  /// Small headings and card titles.
  static const double titleSmall = 18;

  /// Section headings.
  static const double titleMedium = 20;

  /// Prominent page or section titles.
  static const double titleLarge = 24;

  /// Large display text for prominent content.
  static const double display = 32;
}
